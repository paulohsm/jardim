// --- TOTP secrets (RFC 6238) ---
// Up to 8 independent secrets. Each one is a Base32-encoded string (the
// same format any authenticator app — Google Authenticator, Authy,
// FreeOTP, etc. — expects when you add an account by typing a "setup
// key" manually instead of scanning a QR code). This is NOT a password
// you invent yourself: it needs to be randomly generated bytes, encoded
// in Base32. Leave a slot as an empty string ("") if you don't need it —
// an empty slot is always ignored by the firmware.
//
// A slot doesn't have to mean "one person": the same secret can be
// loaded into more than one of your own devices/apps if you want, and a
// device/install you personally use (e.g. a second PC) can get its own
// dedicated slot instead, purely for your own organization — the cost
// per slot is a few dozen bytes, so there's no reason to economize here.
